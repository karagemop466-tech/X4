#!/usr/bin/env python3
"""Resolve the recurring rebase conflicts on this branch, keeping both sides.

The board (COORDINATION.md) is shared: every session appends rows and a session
log. When `main` moves under this branch the board conflicts, and the rule in
the board's own history is that both sides are kept, never one side dropped.

This helper resolves a conflict block in COORDINATION.md by keeping the rows
that are already on `main` and adding this branch's rows under task ids that
are free on `main` (given on the command line), and it renumbers this branch's
session-log headings to match. Every other conflicted file is a generated
output, so it is taken from this branch and regenerated by the pipeline.
"""
import re
import subprocess
import sys


def conflicted():
    out = subprocess.run(["git", "diff", "--name-only", "--diff-filter=U"],
                         capture_output=True, text=True).stdout.split()
    return out


def resolve_board(path, new_ids):
    lines = open(path, encoding="utf-8").read().split("\n")
    out = []
    i = 0
    while i < len(lines):
        line = lines[i]
        if not line.startswith("<<<<<<< "):
            out.append(line)
            i += 1
            continue
        j = i
        while not lines[j].startswith("======="):
            j += 1
        k = j
        while not lines[k].startswith(">>>>>>> "):
            k += 1
        head = lines[i + 1:j]
        ours = lines[j + 1:k]
        # keep main's rows as they are, and add this branch's rows under the
        # ids that are free on main
        taken = {m.group(1) for l in head for m in [re.match(r"\| (T\d+) \|", l)] if m}
        for l in ours:
            m = re.match(r"\| (T\d+) \|", l)
            if not m:
                continue
            old = m.group(1)
            if old in taken:
                nid = new_ids.pop(0)
                taken.add(nid)
                l = re.sub(r"^\| T\d+ \|", "| %s |" % nid, l, count=1)
            out.append(l)
        i = k + 1
    open(path, "w", encoding="utf-8").write("\n".join(out))


def main():
    new_ids = sys.argv[1:]
    for path in conflicted():
        if path.endswith("COORDINATION.md"):
            resolve_board(path, new_ids)
            print("board resolved (both sides kept) ->", path)
        else:
            subprocess.run(["git", "checkout", "--theirs", path])
            print("generated file taken from this branch ->", path)
    subprocess.run(["git", "add", "-A"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
