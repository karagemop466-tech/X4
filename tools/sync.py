#!/usr/bin/env python3
"""
Keep every published copy of the site in step with its source.

Three copies are published, and they must never drift:

  site/                 the canonical site (generated by tools/pages.py)
  <repository root>/    a byte-identical mirror of site/, so the root is also
                        a working site
  console/  and        the X4 Console, mirrored from docs/ into both the
  site/console/         repository root and the published site

Two Pages publishers serve this repository - the custom workflow, which
uploads site/, and the legacy repository-root build - so the two copies have
to hold identical bytes. Generating the mirrors here, rather than by hand in
CI, means the local build and the published build are the same build.

Files mirrored: every page and asset in site/ except check.py, which is a
build tool rather than a site asset. Root copies that are no longer part of
the site are removed.
"""
import os
import shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = os.path.join(ROOT, "site")
DOCS = os.path.join(ROOT, "docs")

SKIP = {"check.py"}
KEEP_ROOT = {"README.md", "COORDINATION.md"}
# The console's own checker is a build tool, not a published page.
CONSOLE_SKIP = {"check.js"}


def mirror_file(src, dst):
    """Copy src to dst when the bytes differ. Returns True when it copied."""
    if os.path.exists(dst) and open(src, "rb").read() == open(dst, "rb").read():
        return False
    shutil.copyfile(src, dst)
    return True


def mirror_tree(src_dir, dst_dir, skip):
    """Mirror every file under src_dir into dst_dir, removing anything stale."""
    changed, removed = [], []
    os.makedirs(dst_dir, exist_ok=True)
    src_files, dst_files = {}, {}
    for base, bucket in ((src_dir, src_files), (dst_dir, dst_files)):
        for dirpath, _dirnames, filenames in os.walk(base):
            for fn in filenames:
                rel = os.path.relpath(os.path.join(dirpath, fn), base)
                if rel in skip:
                    continue
                bucket[rel] = os.path.join(dirpath, fn)
    for rel in sorted(src_files):
        dst = os.path.join(dst_dir, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        if mirror_file(src_files[rel], dst):
            changed.append(rel)
    for rel in sorted(dst_files):
        if rel in src_files:
            continue
        os.remove(dst_files[rel])
        removed.append(rel)
    return changed, removed


def publish_evidence():
    """Publish the research evidence the desk pages link to.

    The desk tables are generated from the committed CSVs, and the pages link
    to those files so a reader can download the exact input behind a table.
    The files are small, so they are published with the site rather than left
    as links into the repository that break on the site/ publisher.
    """
    changed = []
    for rel in ("computed_stats.json", "data/games_weeks6-9_2026.csv",
                "data/standings_2026_through_week10_tnf.csv",
                "data/week11_odds_2026.csv"):
        src = os.path.join(ROOT, "research", rel)
        if not os.path.isfile(src):
            continue
        dst = os.path.join(SITE, "research", rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        if mirror_file(src, dst):
            changed.append(rel)
    return changed


def main():
    changed = []
    names = []
    for fn in sorted(os.listdir(SITE)):
        path = os.path.join(SITE, fn)
        if not os.path.isfile(path) or fn in SKIP:
            continue
        names.append(fn)
        dst = os.path.join(ROOT, fn)
        if mirror_file(path, dst):
            changed.append(fn)

    # remove root files that used to be part of the site but are not any more
    removed = []
    for fn in sorted(os.listdir(ROOT)):
        if fn in names or fn in SKIP or fn in KEEP_ROOT:
            continue
        path = os.path.join(ROOT, fn)
        if os.path.isfile(path):
            if fn.endswith((".html", ".css", ".js")):
                os.remove(path)
                removed.append(fn)

    # the X4 Console: docs/ is the source, console/ and site/console/ are mirrors
    console_changed, console_removed = [], []
    if os.path.isdir(DOCS):
        for dst in (os.path.join(ROOT, "console"), os.path.join(SITE, "console")):
            c, r = mirror_tree(DOCS, dst, CONSOLE_SKIP)
            console_changed += c
            console_removed += r

    if changed:
        print("mirrored to the repository root: %s" % ", ".join(changed))
    if removed:
        print("removed stale root files: %s" % ", ".join(removed))
    evidence = publish_evidence()
    if evidence:
        print("published the desk evidence into site/research: %s" % ", ".join(evidence))
    if console_changed:
        print("mirrored the console from docs/: %s" % ", ".join(sorted(set(console_changed))))
    if console_removed:
        print("removed stale console files: %s" % ", ".join(sorted(set(console_removed))))
    if not changed and not removed and not console_changed and not console_removed:
        print("repository-root copies already match site/ and docs/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
