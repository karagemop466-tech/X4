  function pageLines() {
    var L = D.wk11_lines || [], strat = D.strategies || [];
    var t = byId("lines");
    if (t) {
      table(t, [{ label: "Date" }, { label: "Matchup" }, { label: "Kickoff" }, { label: "TV" },
      { label: "Model spread range", num: true }, { label: "Model total range", num: true },
      { label: "Recommended line (S3)", num: true }, { label: "Market line" }, { label: "Source" }],
        L.map(function (r) {
          var sp = [], to = [];
          strat.forEach(function (s) { var m = r.models[s.id]; if (m) { sp.push(m.spread); to.push(m.total); } });
          var s3 = r.models.S3 || {};
          var minS = Math.min.apply(null, sp), maxS = Math.max.apply(null, sp);
          var minT = Math.min.apply(null, to), maxT = Math.max.apply(null, to);
          return [
            esc(r.date),
            "<b>" + esc(r.away) + " @ " + esc(r.home) + "</b>",
            esc(r.time_et), esc(r.network) + (r.international ? " (" + esc(r.international) + ")" : ""),
            n(minS, 1) + " to " + n(maxS, 1),
            n(minT, 1) + " to " + n(maxT, 1),
            n(s3.spread, 1) + " / " + n(s3.total, 1),
            blank("no official NFL source — see Flagged F-01"),
            src(r.url, "NFL.com")
          ];
        }), { note: "Spreads and totals are MODEL ESTIMATES produced by tools/build.py from official NFL.com results; the range spans all nine strategies. The market-line column is intentionally blank: the NFL does not publish official betting lines, and no licensed odds feed has been authorised for this repository." });
    }

    var s = byId("strat-list");
    if (s) {
      table(s, [{ label: "ID" }, { label: "Strategy" }, { label: "Family" }, { label: "What it does" }, { label: "Input source" }],
        (D.strategies || []).map(function (x) {
          return [esc(x.id), "<b>" + esc(x.name) + "</b>", esc(x.family), esc(x.description), src(SRC_SEASON, "NFL.com results")];
        }), { note: "Every strategy produces a spread and a total for every game. Parameters are listed on the Methodology page." });
    }
  }

  function pageStrategies() {
    var lb = D.leaderboard || [], ce = D.correlation_error || {}, cp = D.correlation_prediction || {},
      cal = D.calibration || {}, wk = D.weekly || {}, ids = (D.strategies || []).map(function (s) { return s.id; });

    var t = byId("lb");
    if (t) {
      table(t, [{ label: "Rank" }, { label: "ID" }, { label: "Strategy" }, { label: "Spread MAE", num: true },
      { label: "Total MAE", num: true }, { label: "Direction acc.", num: true },
      { label: "Improvement", num: true }, { label: "95% CI", num: true }, { label: "Weeks improved", num: true },
      { label: "Calibration gap", num: true }, { label: "Gates" }, { label: "Eligible" }, { label: "Points" }, { label: "Source" }],
        lb.map(function (r, i) {
          return [String(i + 1), esc(r.id), "<b>" + esc(r.name) + "</b>",
            n(r.metrics.spread_mae, 2), n(r.metrics.total_mae, 2), pct(r.metrics.direction_accuracy, 1),
            r.id === "S0" ? badge("benchmark", "mute") : pct(r.improvement_pct, 1),
            n(r.ci_low, 2) + " to " + n(r.ci_high, 2),
            pct(r.weekly_positive_share, 0),
            n(r.calibration_max_gap, 3),
            badge(r.gates_passed + "/7", r.gates_passed === 7 ? "ok" : "warn"),
            r.eligible ? badge("yes", "ok") : badge("no", "no"),
            n(r.reward, 1), src(SRC_SEASON, "NFL.com results")];
        }), { note: "Improvement is the reduction in spread MAE against the S0 league-constant benchmark, measured over " + (D.meta ? D.meta.eval_games : "") + " out-of-sample games. The confidence interval is a " + n((D.meta && D.meta.bonferroni_alpha) ? D.meta.bonferroni_alpha : 0.006, 4) + " Bonferroni-adjusted paired bootstrap interval. Points are provisional: they are only bankable by a strategy that passes all seven gates." });
    }

    var g = byId("gates");
    if (g) {
      var keys = Object.keys(lb[0] ? lb[0].gates : {});
      var rows = [];
      keys.forEach(function (k) {
        lb.forEach(function (r) {
          rows.push([esc(k), esc(r.id), badge(r.gates[k].pass_ ? "pass" : "fail", r.gates[k].pass_ ? "ok" : "no"), esc(r.gates[k].note), src(SRC_SEASON, "NFL.com results")]);
        });
      });
      table(g, [{ label: "Gate" }, { label: "Strategy" }, { label: "Result" }, { label: "Evidence" }, { label: "Source" }], rows,
        { note: "G4 significance is the gate that keeps luck out of the leaderboard: a strategy whose improvement interval still contains zero has not shown skill." });
    }

    function corrTable(elId, matrix, title) {
      var el = byId(elId);
      if (!el) return;
      var head = "<thead><tr><th>Strategy</th>" + ids.map(function (i) { return "<th>" + i + "</th>"; }).join("") + "</tr></thead><tbody>";
      var body = ids.map(function (a) {
        return '<tr><th><a href="' + esc(SRC_SEASON) + '" target="_blank" rel="noreferrer noopener">' + a + "</a></th>" + ids.map(function (b) {
          var v = matrix[a] ? matrix[a][b] : null;
          if (v === null || v === undefined) return "<td>—</td>";
          var c = v > 0.999 ? "background:rgba(239,107,107,.34)" : v > 0.9 ? "background:rgba(240,169,56,.26)"
            : v > 0.6 ? "background:rgba(77,163,255,.16)" : "background:rgba(57,192,127,.13)";
          return '<td style="' + c + '">' + v.toFixed(2) + "</td>";
        }).join("") + "</tr>";
      }).join("");
      el.innerHTML = '<div class="table-wrap"><table class="corr">' + head + body + "</table></div>";
    }
    corrTable("corr-err", ce);
    corrTable("corr-pred", cp);

    var c = byId("calib");
    if (c) {
      var rows = [];
      Object.keys(cal).forEach(function (k) {
        (cal[k].rows || []).forEach(function (r) {
          rows.push([esc(k), n(r.delta, 0), pct(r.predicted, 1), pct(r.observed, 1), n(r.n), badge(r.gap <= 0.12 ? "within tolerance" : "outside tolerance", r.gap <= 0.12 ? "ok" : "no"), src(SRC_SEASON, "NFL.com results")]);
        });
      });
      table(c, [{ label: "Strategy" }, { label: "Offset (pts)", num: true }, { label: "Model says", num: true },
      { label: "Actually happened", num: true }, { label: "Games", num: true }, { label: "Result" }, { label: "Source" }],
        rows, { note: "Reliability check: for each offset the model states the probability that the true total exceeded model total + offset. A well-calibrated model matches the observed rate. Largest gap across offsets is the calibration gap used in gate G6." });
    }

    var w = byId("weekly");
    if (w) {
      var weeks = [];
      (wk.S0 ? wk.S0.per_week : []).forEach(function (_, i) { weeks.push(i); });
      var rows = [];
      lb.forEach(function (r) {
        (wk[r.id] ? wk[r.id].per_week : []).forEach(function (v, i) {
          rows.push([esc(r.id), "Week " + (D.meta && D.meta.eval_weeks ? D.meta.eval_weeks[0] + i : i), n(v, 2), badge(v > 0 ? "better" : (v < 0 ? "worse" : "even"), v > 0 ? "ok" : (v < 0 ? "no" : "mute")), src(SRC_SEASON, "NFL.com results")]);
        });
      });
      table(w, [{ label: "Strategy" }, { label: "Week" }, { label: "Spread MAE improvement vs S0", num: true }, { label: "Direction" }, { label: "Source" }], rows,
        { note: "Week-by-week stability. Gate G5 requires the improvement to be positive in at least 60% of evaluated weeks." });
    }
  }

